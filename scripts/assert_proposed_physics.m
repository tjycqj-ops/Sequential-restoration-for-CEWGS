function report = assert_proposed_physics(result_file,case_file,tolerance)
%ASSERT_PROPOSED_PHYSICS Check the three nonlinear-physics gaps in a result.

if nargin < 3
    tolerance = 0.1;
end
validateattributes(tolerance,{'numeric'},{'scalar','finite','nonnegative'});
result = load(result_file);
data = load(case_file);

ordinary_water = setdiff((1:size(data.WDS_pipe,1))', ...
    data.WDS_pump(:,1),'stable');
water_kappa = repmat(data.WDS_pipe(ordinary_water,8),1,result.TT);
water_positive_gap = result.water_hP_r- ...
    water_kappa.*result.water_qP_r.^2;
water_negative_gap = result.water_hM_r- ...
    water_kappa.*result.water_qM_r.^2;
water_gap = max([water_positive_gap;water_negative_gap],[],'all');

ordinary_gas = setdiff((1:size(data.GDS_pipe,1))', ...
    data.GDS_compessor(:,1),'stable');
gas_scaled_flow = result.G_ijave_r(ordinary_gas,:)./ ...
    repmat(data.GDS_pipe(ordinary_gas,4),1,result.TT);
gas_gap_values = result.kesai_ijH_r.^2-result.kesai_ijL_r.^2- ...
    gas_scaled_flow.^2;
gas_gap = max(abs(gas_gap_values),[],'all');

pump_gap = max(abs(result.pump_slack_r),[],'all');
report = struct('tolerance',tolerance,'water_gap_m',water_gap, ...
    'gas_gap_bar2',gas_gap,'pump_gap_kW',pump_gap, ...
    'passed',water_gap<=tolerance&&gas_gap<=tolerance&& ...
    pump_gap<=tolerance);

fprintf(['Physics gaps: water %.6g m, gas %.6g bar^2, ', ...
    'pump %.6g kW (tolerance %.6g).\n'],water_gap,gas_gap,pump_gap,tolerance);
assert(report.passed,'CEWGS:PhysicsGapExceeded', ...
    ['Physical-gap acceptance failed: water %.6g m, gas %.6g bar^2, ', ...
    'pump %.6g kW; tolerance %.6g.'], ...
    water_gap,gas_gap,pump_gap,tolerance);
end
